export function t(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.pt;
  let str = dict[key] ?? STRINGS.pt[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) str = str.replaceAll('%' + k, v);
  }
  return str;
}
